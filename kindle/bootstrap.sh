#!/usr/bin/env bash
# Provision a jailbroken Kindle as a kitchen dashboard, from scratch.
#
# Usage:
#   kindle/bootstrap.sh [kindle-ip]
#
# Reads .env in the repo root for defaults:
#   KINDLE_HOST             Kindle IP (or pass as first argument)
#   KINDLE_USER             SSH user (default: root)
#   KINDLE_PASSWORD         if set, uses sshpass for password auth
#   DASHBOARD_SERVER_URL    where the Kindle pulls images from
#                           (e.g. http://192.168.1.201:8090)
#   DASHBOARD_TRIGGER_URL   hard-refresh endpoint (e.g. http://192.168.1.201:8091)
#
# What it does:
#   1. copies the payload scripts + generated config.sh to /mnt/us/dashboard/
#   2. installs the fetch cron job and a boot hook (persists across reboots)
#   3. enters dashboard mode (stops stock UI, starts button daemon)
#   4. runs an initial image fetch (leaving WiFi on for this session)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$REPO_DIR/.env"

env_get() {
    [ -f "$ENV_FILE" ] || return 0
    sed -n "s/^$1=//p" "$ENV_FILE" | tail -1 | tr -d '"'
}

KINDLE_HOST="${1:-$(env_get KINDLE_HOST)}"
KINDLE_USER="$(env_get KINDLE_USER)"; KINDLE_USER="${KINDLE_USER:-root}"
KINDLE_PASSWORD="$(env_get KINDLE_PASSWORD)"
SERVER_URL="$(env_get DASHBOARD_SERVER_URL)"
TRIGGER_URL="$(env_get DASHBOARD_TRIGGER_URL)"
FETCH_INTERVAL_MIN="${FETCH_INTERVAL_MIN:-30}"

if [ -z "$KINDLE_HOST" ]; then
    echo "Error: no Kindle IP. Pass it as an argument or set KINDLE_HOST in .env" >&2
    exit 1
fi
if [ -z "$SERVER_URL" ]; then
    echo "Error: DASHBOARD_SERVER_URL not set in .env (e.g. http://192.168.1.201:8090)" >&2
    exit 1
fi

SSH_OPTS=(-o StrictHostKeyChecking=accept-new -o ConnectTimeout=10)
if [ -n "$KINDLE_PASSWORD" ]; then
    if ! command -v sshpass >/dev/null; then
        echo "Error: KINDLE_PASSWORD is set but sshpass is not installed" >&2
        exit 1
    fi
    kssh() { sshpass -p "$KINDLE_PASSWORD" ssh "${SSH_OPTS[@]}" "$KINDLE_USER@$KINDLE_HOST" "$@"; }
    kscp() { sshpass -p "$KINDLE_PASSWORD" scp "${SSH_OPTS[@]}" "$@"; }
else
    kssh() { ssh "${SSH_OPTS[@]}" "$KINDLE_USER@$KINDLE_HOST" "$@"; }
    kscp() { scp "${SSH_OPTS[@]}" "$@"; }
fi

echo "== Testing connection to $KINDLE_USER@$KINDLE_HOST =="
kssh "echo connected to \$(cat /proc/usid 2>/dev/null || hostname)"

echo "== Generating config.sh =="
TMP_CONFIG="$(mktemp)"
trap 'rm -f "$TMP_CONFIG"' EXIT
cat > "$TMP_CONFIG" <<EOF
# Generated by bootstrap.sh on $(date '+%Y-%m-%d %H:%M') - edit on the Kindle
# at /mnt/us/dashboard/config.sh, or re-run bootstrap to regenerate.

# cron/init and non-interactive SSH get PATH=/usr/bin:/bin, but eips and
# mntroot live in /usr/sbin - extend PATH for every script sourcing this.
export PATH="/usr/sbin:/sbin:\$PATH"

SERVER_URL="$SERVER_URL"
TRIGGER_URL="$TRIGGER_URL"
IMAGE_DIR=/mnt/us/dashboard/images
LOG_FILE=/mnt/us/dashboard/dashboard.log
KEEP_WIFI=0
FETCH_INTERVAL_MIN=$FETCH_INTERVAL_MIN

# Button keycodes (space-separated lists). Defaults cover common Kindle 4
# values; run identify-keys.sh on the device to find yours if these are off.
NEXT_CODES="106 109"        # 5-way right, page forward
PREV_CODES="105 104"        # 5-way left, page back
REFRESH_CODES="194 28 96"   # 5-way center / select
REDRAW_CODES="102"          # Home button
EOF

echo "== Copying payload to /mnt/us/dashboard/ =="
kssh "mkdir -p /mnt/us/dashboard/images"
kscp "$SCRIPT_DIR"/payload/*.sh "$KINDLE_USER@$KINDLE_HOST:/mnt/us/dashboard/"
kscp "$TMP_CONFIG" "$KINDLE_USER@$KINDLE_HOST:/mnt/us/dashboard/config.sh"

echo "== Running device setup (cron + boot hook) =="
kssh "sh /mnt/us/dashboard/setup-on-kindle.sh"

echo "== Entering dashboard mode =="
kssh "sh /mnt/us/dashboard/start-dashboard.sh"

echo "== Initial image fetch (keeping WiFi on for now) =="
kssh "sh /mnt/us/dashboard/fetch-images.sh keepwifi" || {
    echo "Initial fetch failed - is the server rendering images at $SERVER_URL ?"
    echo "The cron job will retry every $FETCH_INTERVAL_MIN minutes."
}

cat <<EOF

== Bootstrap complete ==

The Kindle is now in dashboard mode. Notes:
 - WiFi will turn OFF after the next cron fetch (every $FETCH_INTERVAL_MIN min).
   To SSH in later: press the center button and connect while WiFi is up,
   or reboot and connect before the first fetch.
 - To keep WiFi on for maintenance:
     ssh $KINDLE_USER@$KINDLE_HOST touch /mnt/us/dashboard/.keepwifi
 - Buttons: left/right = prev/next screen, center = hard refresh,
   Home = redraw. If buttons don't respond correctly, run:
     ssh $KINDLE_USER@$KINDLE_HOST sh /mnt/us/dashboard/identify-keys.sh
   then update the *_CODES values in /mnt/us/dashboard/config.sh and re-run:
     ssh $KINDLE_USER@$KINDLE_HOST sh /mnt/us/dashboard/start-dashboard.sh
 - Logs: ssh $KINDLE_USER@$KINDLE_HOST tail -f /mnt/us/dashboard/dashboard.log
EOF
